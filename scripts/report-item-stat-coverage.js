#!/usr/bin/env node
// Runs lib/item-stats.ts over every data/items.json tooltip and reports how
// much parses cleanly, split by equipment vs. everything else, with the
// failing line shapes. Read-only on data; writes docs/item-stat-coverage.md.
//
// "Clean" = every tooltip line was classified (no `unparsed` lines) and no
// expected field is missing (armor on cloth/leather/mail/plate/shield,
// damage on a weapon). Equip:/Use: text that isn't a plain stat is counted
// separately as "has unmodelled effects": its stats are still right, the
// effect just isn't scored.
//
// Usage: node scripts/report-item-stat-coverage.js [--json]

const fs = require("fs");
const path = require("path");
const { parseItemTooltip } = require("../lib/item-stats.ts");

const ROOT = path.join(__dirname, "..");
const { items } = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "items.json"), "utf8"));
const OUT = path.join(ROOT, "docs", "item-stat-coverage.md");

const ARMORED = /\t(Cloth|Leather|Mail|Plate|Shield)$/;
const NO_DAMAGE_WEAPON = /^(Ammo|Projectile)$/;
const shape = (line) => line.replace(/\d+(\.\d+)?/g, "N").replace(/\t/g, " ⇥ ");

function missingFields(item, parsed) {
  const missing = [];
  if (item.tooltip.some((l) => ARMORED.test(l)) && parsed.armor === 0) missing.push("armor");
  if (item.itemClass === 2 && !NO_DAMAGE_WEAPON.test(item.slot ?? "") && !parsed.weapon?.damage.length)
    missing.push("weapon damage");
  if (parsed.weapon?.damage.length && parsed.weapon.dps === null) missing.push("dps");
  return missing;
}

function newBucket() {
  return { total: 0, clean: 0, unparsedItems: 0, missingItems: 0, withEffects: 0, lineShapes: new Map(), effectShapes: new Map(), missing: new Map(), examples: new Map() };
}

const buckets = { equipment: newBucket(), other: newBucket() };
const byStatus = {};
for (const item of items) {
  const parsed = parseItemTooltip(item.tooltip);
  const isEquipment = (item.itemClass === 2 || item.itemClass === 4) && item.slot !== null;
  const b = buckets[isEquipment ? "equipment" : "other"];
  const missing = missingFields(item, parsed);
  b.total++;
  if (parsed.effects.length) b.withEffects++;
  if (parsed.unparsed.length) b.unparsedItems++;
  if (missing.length) b.missingItems++;
  for (const f of missing) {
    b.missing.set(f, (b.missing.get(f) ?? 0) + 1);
    if (!b.examples.has(`missing:${f}`)) b.examples.set(`missing:${f}`, item);
  }
  for (const line of parsed.effects) {
    const s = shape(line);
    b.effectShapes.set(s, (b.effectShapes.get(s) ?? 0) + 1);
  }
  for (const line of parsed.unparsed) {
    const s = shape(line);
    b.lineShapes.set(s, (b.lineShapes.get(s) ?? 0) + 1);
    if (!b.examples.has(s)) b.examples.set(s, item);
  }
  const clean = !parsed.unparsed.length && !missing.length;
  if (clean) b.clean++;
  if (isEquipment) {
    const k = item.tooltipSynthesized ? `${item.status} (synthesized tooltip)` : item.status;
    byStatus[k] ??= { total: 0, clean: 0 };
    byStatus[k].total++;
    if (clean) byStatus[k].clean++;
  }
}

const pct = (a, b) => (b ? ((100 * a) / b).toFixed(1) : "0.0") + "%";
const top = (map, n) => [...map.entries()].sort((a, b) => b[1] - a[1]).slice(0, n);

if (process.argv.includes("--json")) {
  const plain = (b) => ({ ...b, lineShapes: top(b.lineShapes, 50), effectShapes: top(b.effectShapes, 50), missing: [...b.missing], examples: undefined });
  console.log(JSON.stringify({ equipment: plain(buckets.equipment), other: plain(buckets.other), byStatus }, null, 2));
  process.exit(0);
}

const md = [];
md.push("# Item tooltip → stats parse coverage", "");
md.push(`Generated by \`scripts/report-item-stat-coverage.js\` from \`data/items.json\` (${items.length} items) with \`lib/item-stats.ts\`. Re-run after every item pull.`, "");
md.push("Equipment = weapons and armor (`itemClass` 2 or 4) with a slot. Clean = every line classified and no expected field (armor, weapon damage, DPS) missing.", "");
md.push("| Group | Items | Clean | Unparsed lines | Missing a field | Has unmodelled effects |", "|---|---|---|---|---|---|");
for (const [name, b] of Object.entries(buckets))
  md.push(`| ${name} | ${b.total} | ${b.clean} (${pct(b.clean, b.total)}) | ${b.unparsedItems} | ${b.missingItems} | ${b.withEffects} (${pct(b.withEffects, b.total)}) |`);
md.push("", "## Equipment by item status", "", "| Status | Items | Clean |", "|---|---|---|");
for (const [k, v] of Object.entries(byStatus).sort((a, b) => b[1].total - a[1].total))
  md.push(`| ${k} | ${v.total} | ${v.clean} (${pct(v.clean, v.total)}) |`);
for (const [name, b] of Object.entries(buckets)) {
  md.push("", `## ${name}: missing fields`, "");
  if (!b.missing.size) md.push("None.");
  for (const [f, n] of top(b.missing, 10)) {
    const ex = b.examples.get(`missing:${f}`);
    md.push(`- **${f}**: ${n} items (e.g. ${ex.itemId} ${ex.name}: \`${ex.tooltip.join(" | ")}\`)`);
  }
  if (name === "equipment") {
    md.push("", "## equipment: unmodelled effect lines (top 40)", "", "Not counted as failures: procs, on-use, conditional and ability-specific bonuses. Listed so a stat-shaped line hiding here is easy to spot.", "");
    for (const [s, n] of top(b.effectShapes, 40)) md.push(`- ${n} × \`${s}\``);
  }
  md.push("", `## ${name}: unparsed line shapes (top 40)`, "");
  if (!b.lineShapes.size) md.push("None.");
  for (const [s, n] of top(b.lineShapes, 40)) {
    const ex = b.examples.get(s);
    md.push(`- ${n} × \`${s}\` (e.g. ${ex.itemId} ${ex.name})`);
  }
}
fs.writeFileSync(OUT, md.join("\n") + "\n");
for (const [name, b] of Object.entries(buckets))
  console.log(`${name}: ${b.clean}/${b.total} clean (${pct(b.clean, b.total)}), unparsed ${b.unparsedItems}, missing ${b.missingItems}, effects ${b.withEffects}`);
console.log(`wrote ${path.relative(ROOT, OUT)}`);
