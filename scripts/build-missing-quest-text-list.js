#!/usr/bin/env node
// One-shot report (not wired into any build step) listing every quest in
// data/sources/foreverchanges/quests/list.json that has no cmangos/classic-db
// text match -- the "new to Forever, no Classic-era precedent" set
// (data/sources/cmangos/quest-text.json's own 4,204/5,049-matched stat).
// Run with `npx tsx scripts/build-missing-quest-text-list.js` (needs tsx for
// the lib/zone-areas.ts TS import). Output:
// data/sources/foreverchanges/quests/missing-cmangos-text.json

import fs from "fs";
import path from "path";
import { getZoneName } from "../lib/zone-areas.ts";

const QUESTS_FILE = path.join(process.cwd(), "data", "sources", "foreverchanges", "quests", "list.json");
const CMANGOS_FILE = path.join(process.cwd(), "data", "sources", "cmangos", "quest-text.json");
const OUT_FILE = path.join(
  process.cwd(),
  "data",
  "sources",
  "foreverchanges",
  "quests",
  "missing-cmangos-text.json",
);

const list = JSON.parse(fs.readFileSync(QUESTS_FILE, "utf8"));
const cmangos = JSON.parse(fs.readFileSync(CMANGOS_FILE, "utf8")).quests;

const LOCATION_LABEL = { zone: "zone", dungeon: "dungeon", raid: "raid", battleground: "battleground", sort: "other" };

const missing = list
  .filter((q) => !Object.prototype.hasOwnProperty.call(cmangos, String(q.i)))
  .map((q) => {
    const [locationKind, locationId] = q.c ?? [null, null];
    const locationName = locationKind === "zone" && locationId !== null ? getZoneName(locationId) : null;
    return {
      id: q.i,
      name: q.n,
      level: q.l || null,
      requiredLevel: q.m || null,
      location: locationName ?? (locationKind ? `${LOCATION_LABEL[locationKind] ?? locationKind} #${locationId}` : null),
    };
  })
  .sort((a, b) => a.id - b.id);

fs.writeFileSync(
  OUT_FILE,
  JSON.stringify(
    {
      description:
        "Quests in data/sources/foreverchanges/quests/list.json with no matching row in data/sources/cmangos/quest-text.json -- new to Forever, no Classic-era precedent. Generated by scripts/build-missing-quest-text-list.js.",
      generatedDate: new Date().toISOString().slice(0, 10),
      count: missing.length,
      quests: missing,
    },
    null,
    1,
  ),
);
console.log(`Wrote ${missing.length} quests to ${path.relative(process.cwd(), OUT_FILE)}`);
