// Generates lib/map-data.generated.ts: static JSON imports of every
// data/map/<continent>/{meta,zones,zone-areas}.json. Static imports are
// bundled into the build instead of being read from disk at request time via
// a runtime-variable path (which would make file tracing include whole
// directories -- see CLAUDE.md's standing rule). Runs as `prebuild`.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const mapDir = path.join(root, "data", "map");
const ids = fs
  .readdirSync(mapDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .filter((id) => ["meta", "zones", "zone-areas"].every((f) => fs.existsSync(path.join(mapDir, id, f + ".json"))))
  .sort();

const ident = (id) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const lines = ["// GENERATED by scripts/build-map-data-imports.js (runs as `prebuild`) -- do not edit."];
for (const id of ids) {
  for (const [f, v] of [["meta", "Meta"], ["zones", "Zones"], ["zone-areas", "Areas"]]) {
    lines.push(`import ${ident(id)}${v} from "@/data/map/${id}/${f}.json";`);
  }
}
lines.push("", "export const MAP_DATA: Record<string, { meta: object; zones: object; areas: object }> = {");
for (const id of ids) lines.push(`  ${JSON.stringify(id)}: { meta: ${ident(id)}Meta, zones: ${ident(id)}Zones, areas: ${ident(id)}Areas },`);
lines.push("};", "");
fs.writeFileSync(path.join(root, "lib", "map-data.generated.ts"), lines.join("\n"));
console.log(`map-data: ${ids.length} continents`);
