// Generates lib/og-backgrounds.generated.ts: a static map of every OG
// background image (path -> a readFile call with a LITERAL path). File
// tracing can only resolve literal paths -- a runtime-variable
// path.join(process.cwd(), "public", x) makes it include all of public/
// (100+ MB of map tiles/images) in every serverless function.
// Each source image is also pre-shrunk here (1600px-wide JPEG q82) into
// assets/og-backgrounds/, so the runtime never needs sharp (~10MB of native
// binaries) and traces only the small shrunken files, not full-res heroes.
// Why JPEG: satori (next/og) can't decode WebP data URIs and chokes on
// oversized buffers (both confirmed failures).
// Runs automatically as `prebuild`, so new content heroes never drift.
const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");
const sharp = require("sharp");

const root = path.join(__dirname, "..");
const paths = new Set(["/images/hero/homepage-hero.webp"]);

// Hardcoded backgrounds passed from opengraph-image.tsx files.
const appDir = path.join(root, "app");
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/opengraph-image\.tsx$/.test(e.name)) {
      for (const m of fs.readFileSync(p, "utf8").matchAll(/backgroundImage:\s*"(\/[^"]+)"/g)) paths.add(m[1]);
    }
  }
})(appDir);

// Frontmatter heroImage from every content type.
const contentDir = path.join(root, "content");
for (const dir of fs.readdirSync(contentDir)) {
  const full = path.join(contentDir, dir);
  if (!fs.statSync(full).isDirectory()) continue;
  for (const f of fs.readdirSync(full).filter((n) => n.endsWith(".mdx"))) {
    const { data } = matter(fs.readFileSync(path.join(full, f), "utf8"));
    if (typeof data.heroImage === "string" && data.heroImage.startsWith("/")) paths.add(data.heroImage);
  }
}

const outDir = path.join(root, "assets", "og-backgrounds");
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const existing = [...paths].sort().filter((p) => fs.existsSync(path.join(root, "public", p)));

(async () => {
  const lines = [];
  for (const p of existing) {
    const name = p.replace(/^\//, "").replace(/\//g, "__").replace(/\.[^.]+$/, "") + ".jpg";
    await sharp(path.join(root, "public", p))
      .resize({ width: 1600, withoutEnlargement: true })
      .jpeg({ quality: 82 })
      .toFile(path.join(outDir, name));
    lines.push(
      `  ${JSON.stringify(p)}: () => fs.readFile(path.join(process.cwd(), ${JSON.stringify("assets/og-backgrounds/" + name)})),`
    );
  }
  const header = [
    "// GENERATED by scripts/build-og-backgrounds.js (runs as `prebuild`) -- do not edit.",
    "// Values are pre-shrunk JPEGs (assets/og-backgrounds/), ready to embed as data URIs.",
    'import fs from "fs/promises";',
    'import path from "path";',
    "",
    "export const OG_BACKGROUNDS: Record<string, () => Promise<Buffer>> = {",
  ];
  fs.writeFileSync(
    path.join(root, "lib", "og-backgrounds.generated.ts"),
    [...header, ...lines, "};", ""].join("\n")
  );
  console.log(`og-backgrounds: ${existing.length} images`);
})();
