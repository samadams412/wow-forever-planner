// Converts wow.export's per-zone in-game map art (one PNG per zone, 1002x668,
// a fixed-size texture matching the client's own zone-map UI frame) into
// small JPEGs under public/images/zone-maps/<areaId>.jpg for the quest-detail
// mini-map (components/reference/QuestMap.tsx). Source lives outside
// the repo entirely on the machine that ran wow.export (same convention as
// scripts/slice-map-tiles.js), never committed -- only this script's small
// JPEG output is. Unlike the map tile pyramid, these are genuinely small
// (a few hundred KB each after compression) and client-fetched directly via
// <img src>, so they're committed straight to public/ rather than gitignored
// like public/map/*/tiles/.
//
// Pin placement for these images is pure percent-based: Wowhead's own
// x/y (0-100, zone-relative) map directly onto pixel = percent/100 *
// (imageWidth, imageHeight) -- confirmed empirically against a known NPC
// location (Brother Paxton's Elwynn Forest point lands exactly on Northshire
// Abbey). No ADT/world-coordinate math needed, unlike the real tile pyramid
// used by the full /reference/map/[continent] page (untouched by this --
// that page still needs real pan/zoom across a huge continent plus zone
// borders/entrance markers, which this flat per-zone art can't serve).
//
// Usage: node scripts/build-zone-map-images.js

const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const SOURCE_DIR = "C:/Users/samue/wow.export/zones";
const OUT_DIR = path.join(__dirname, "..", "public", "images", "zone-maps");
// Literal-path lookup of which areaIds have an image -- generated here
// (alongside the images themselves) rather than read at runtime via
// fs.readdirSync(variablePath) or fs.existsSync on a per-request areaId,
// either of which would make Next's file tracer bundle the whole
// public/images/zone-maps/ directory into every serverless function that
// imports lib/quests.ts (see CLAUDE.md's standing rule on this).
const GENERATED_FILE = path.join(__dirname, "..", "lib", "zone-map-images.generated.ts");

async function main() {
  if (!fs.existsSync(SOURCE_DIR)) {
    console.error(`Source directory not found: ${SOURCE_DIR}`);
    process.exit(1);
  }
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const files = fs.readdirSync(SOURCE_DIR).filter((f) => /^Zone_\d+_.*\.png$/.test(f));
  let written = 0;
  const dims = new Set();
  const areaIds = [];
  for (const file of files) {
    const match = file.match(/^Zone_(\d+)_/);
    const areaId = Number(match[1]);
    areaIds.push(areaId);
    const srcPath = path.join(SOURCE_DIR, file);
    const image = sharp(srcPath);
    const meta = await image.metadata();
    dims.add(`${meta.width}x${meta.height}`);
    await image.jpeg({ quality: 85 }).toFile(path.join(OUT_DIR, `${areaId}.jpg`));
    written++;
  }
  areaIds.sort((a, b) => a - b);

  fs.writeFileSync(
    GENERATED_FILE,
    [
      "// GENERATED by scripts/build-zone-map-images.js -- do not edit.",
      "// areaIds with a /images/zone-maps/<areaId>.jpg in public/ for the quest-detail mini-map.",
      `export const ZONE_MAP_IMAGE_IDS = new Set<number>(${JSON.stringify(areaIds)});`,
      "",
    ].join("\n")
  );

  console.log(`wrote ${written} zone map image(s) to ${path.relative(process.cwd(), OUT_DIR)}`);
  console.log(`source dimensions seen: ${[...dims].join(", ")}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
