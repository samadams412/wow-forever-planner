import LootItemPill from "@/components/reference/LootItemPill";
import type { LevelingRank } from "@/lib/profession-recipes";

// Matches foreverchanges.pro/professions/<id>#leveling's own layout
// (rank-tier header with its requirement text, then one row per skill
// range: item, source caption, craft count, materials) -- studied live
// before building, not copied markup. The "~N crafts" count string in the
// source data has no space before "crafts" (a scrape artifact, same class
// of bug as the item-tooltip fixes in Part A) -- reformatted at render time
// rather than in the data itself, since this file wasn't generated by this
// site's own pipeline.
export default function ProfessionLevelingGuide({ leveling, professionId }: { leveling: LevelingRank[]; professionId: string }) {
  return (
    <div className="mt-4 flex flex-col gap-4">
      {leveling.map((rank, ri) => (
        <div key={rank.rank} className="rounded-lg border border-border bg-surface">
          <div className="border-b border-border bg-surface-hover/40 px-4 py-2">
            <span className="font-heading text-sm font-semibold uppercase tracking-wide text-accent">{rank.rank}</span>
            <span className="ml-2 text-xs text-foreground-muted">{rank.requirement}</span>
          </div>
          <div className="flex flex-col gap-2.5 p-3">
            {rank.steps.map((step, si) => (
              <div key={si} className="flex flex-wrap items-center gap-x-3 gap-y-1 text-sm">
                <span className="w-16 shrink-0 text-xs font-medium text-foreground-muted">
                  {step.range[0]}&ndash;{step.range[1]}
                </span>
                <LootItemPill item={step.item} tooltipId={`prof:${professionId}:lvl:${ri}:${si}`} context="catalog" />
                <span className="text-xs text-foreground-muted">{step.source}</span>
                <span className="text-xs text-foreground-muted">
                  {step.count.replace(/^(~?\d+)crafts?$/, "$1 crafts")}
                </span>
                <div className="flex flex-wrap gap-1">
                  {step.mats.map((mat, mi) => (
                    <span key={mi} className="inline-flex items-center">
                      <LootItemPill item={mat.item} tooltipId={`prof:${professionId}:lvl:${ri}:${si}:mat:${mi}`} context="catalog" />
                      <span className="ml-0.5 text-[10px] text-foreground-muted">&times;{mat.qty}</span>
                    </span>
                  ))}
                </div>
              </div>
            ))}
          </div>
        </div>
      ))}
    </div>
  );
}
